		fn account_code_at(address: sp_core::H160) -> Vec<u8> {
			pallet_evm::AccountCodes::<Runtime>::get(address)
		}

		fn author() -> sp_core::H160 {
			<pallet_evm::Pallet<Runtime>>::find_author()
		}

		fn storage_at(address: sp_core::H160, index: sp_core::U256) -> sp_core::H256 {
			let tmp = index.to_big_endian();
			pallet_evm::AccountStorages::<Runtime>::get(address, sp_core::H256::from_slice(&tmp[..]))
		}

		fn call(
			from: sp_core::H160,
			to: sp_core::H160,
			data: Vec<u8>,
			value: sp_core::U256,
			gas_limit: sp_core::U256,
			max_fee_per_gas: Option<sp_core::U256>,
			max_priority_fee_per_gas: Option<sp_core::U256>,
			nonce: Option<sp_core::U256>,
			estimate: bool,
			access_list: Option<Vec<(sp_core::H160, Vec<sp_core::H256>)>>,
			authorization_list: Option<ethereum::AuthorizationList>,
		) -> Result<pallet_evm::CallInfo, sp_runtime::DispatchError> {
			use pallet_evm::GasWeightMapping as _;

			let config = if estimate {
				let mut config = <Runtime as pallet_evm::Config>::config().clone();
				config.estimate = true;
				Some(config)
			} else {
				None
			};

			let mut estimated_transaction_len = data.len() + 259;
			if let Some(ref al) = access_list {
				estimated_transaction_len += al.len() * 100; // rough estimation
			}

			let gas_limit = if gas_limit > sp_core::U256::from(u64::MAX) {
				u64::MAX
			} else {
				gas_limit.low_u64()
			};
			let without_base_extrinsic_weight = true;

			let (weight_limit, proof_size_base_cost) =
				match <Runtime as pallet_evm::Config>::GasWeightMapping::gas_to_weight(
					gas_limit,
					without_base_extrinsic_weight
				) {
					weight_limit if weight_limit.proof_size() > 0 => {
						(Some(weight_limit), Some(estimated_transaction_len as u64))
					}
					_ => (None, None),
				};

			<Runtime as pallet_evm::Config>::Runner::call(
				from,
				to,
				data,
				value,
				sp_runtime::traits::UniqueSaturatedInto::unique_saturated_into(gas_limit),
				max_fee_per_gas,
				max_priority_fee_per_gas,
				nonce,
				access_list.unwrap_or_default(),
				authorization_list.unwrap_or_default(),
				false,
				true,
				weight_limit,
				proof_size_base_cost,
				config.as_ref().unwrap_or(<Runtime as pallet_evm::Config>::config()),
			).map_err(|err| err.error.into())
		}

